#!/usr/bin/env python3
"""Write the Supabase migration that loads source/spec_section4.json into the app's
sections, sectors and neighbourhoods tables.

Follows the pattern already used for Kaaraan in the app:
  section       code = section number ("03"), name = system label ("Nageyle KR")
  sector        code = sector number ("01"),  name = "<sector> <location code>" ("Xaaji Laameer KRWJ")
  neighbourhood code = name = full block code ("KRWJXL01"); codes are unique per district.

Districts are matched by name to the app's own district codes, which differ from the LRMIS codes.
Usage: python3 to_app_migration.py <output .sql>
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# LRMIS district name → app districts.code (app names differ in spelling, e.g. "Warta-Nabadda").
APP_DISTRICT = {
    "Dayniile": "04", "Howlwadaag": "09", "Heliwaa": "10", "Wartanabadda": "16", "Hodan": "08",
    "Boondheere": "03", "Cabdicasiis": "02", "Dharkeenley": "05", "Kaaraan": "34", "Shibis": "13",
    "Shingaani": "12", "Wadajir": "15", "Xamarjajab": "06", "Xamarweyne": "07", "Waaberi": "14",
    "Yaaqshiid": "17", "Kaxda": "11", "Daarusalaam": "20", "Gubadleey": "18", "Garasbaalleey": "19",
}
# Weydoow GB has two sectors coded 03 in the LRMIS; the app needs unique codes (user chose 04).
SECTOR_CODE_FIX = {("GBWY", "Macaanteey"): "04"}
# Numbering with gaps (spec §4 notes): the exact block numbers.
GAPS = {
    "DKXBAF": list(range(1, 46)) + [52],
    "DKSRKW": list(range(1, 35)) + [51],
    "DKSRLB": list(range(1, 26)) + [30],
}
# 22 blocks numbered somewhere in 1-79; the spec doesn't say which, so none are created.
UNKNOWN_NUMBERS = {"DSKLCT"}


def q(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    districts = json.loads((HERE / "source" / "spec_section4.json").read_text(encoding="utf-8"))["districts"]
    sections, sectors, n_blocks = [], [], 0
    for d in districts:
        dc = APP_DISTRICT[d["district_name"]]
        abbr = next(s["location_code"][:2] for s in d["sections"] if s["location_code"] != "n/a")
        for s in d["sections"]:
            loc = "" if s["location_code"] == "n/a" else s["location_code"]
            sections.append(f"({q(dc)}, {q(s['section_code'])}, {q(s['section_name'] + ' ' + abbr)}, {q(loc) if loc else 'null'})")
            for t in s["sectors"]:
                code = SECTOR_CODE_FIX.get((loc, t["sector_name"]), t["sector_code"])
                name = f"{t['sector_name']} {loc}" if loc else t["sector_name"]
                prefix = (t["first_code"] or "")[:-2]
                # Blocks are prefix + 01..count, or the listed numbers where numbering has gaps.
                count = 0 if not prefix or prefix in UNKNOWN_NUMBERS else t["neighborhood_count"]
                nums = GAPS.get(prefix)
                assert nums is None or len(nums) == count, prefix
                n_blocks += count
                sectors.append(f"({q(dc)}, {q(s['section_code'])}, {q(code)}, {q(name)}, "
                               f"{q(prefix) if prefix else 'null'}, {count}, "
                               f"{'array[' + ','.join(map(str, nums)) + ']' if nums else 'null'})")

    sql = f"""-- ============================================================================
-- 0103 Banaadir locations: every LRMIS section, sector and block (Location Settings export
-- of 2026-10-25), generated by frontend/location-master-data/to_app_migration.py.
-- {len(sections)} sections · {len(sectors)} sectors · {n_blocks} neighbourhoods.
-- Districts are matched to the app's own codes. Rows that already exist (same code) are kept.
-- Not loaded: the 22 Cali Turcaaye (DSKLCT) blocks, whose numbers the export doesn't give.
-- Weydoow's second sector 03 (Macaanteey) is coded 04. Points aren't stored: geom is polygons.
-- ============================================================================

-- Block codes are unique per district, so Kaaraan's hand-made blocks 01–08 take their full code.
update public.neighbourhoods n
   set code = 'KRWJXL' || n.code, name_so = 'KRWJXL' || n.code, name_en = 'KRWJXL' || n.code
  from public.sectors t
  join public.sections s on s.id = t.section_id
  join public.districts d on d.id = s.district_id
 where n.sector_id = t.id and d.code = '34' and s.code = '04' and t.code = '01' and n.code ~ '^[0-9]{{2}}$';

insert into public.sections (district_id, code, name_so, name_en, legacy_id)
select d.id, v.code, v.name, v.name, v.legacy_id
  from (values
{(','+chr(10)).join('    ' + r for r in sections)}
  ) as v (district_code, code, name, legacy_id)
  join public.districts d on d.code = v.district_code and d.deleted_at is null
on conflict (district_id, code) do nothing;

create temporary table banaadir_sectors (
  district_code text, section_code text, code text, name text, prefix text, block_count int, block_numbers int[]
) on commit drop;

insert into banaadir_sectors values
{(','+chr(10)).join('  ' + r for r in sectors)};

insert into public.sectors (section_id, district_id, code, name_so, name_en, legacy_id)
select s.id, s.district_id, v.code, v.name, v.name, v.prefix
  from banaadir_sectors v
  join public.districts d on d.code = v.district_code and d.deleted_at is null
  join public.sections s on s.district_id = d.id and s.code = v.section_code and s.deleted_at is null
on conflict (section_id, code) do nothing;

insert into public.neighbourhoods (sector_id, district_id, code, name_so, name_en)
select t.id, t.district_id, b.code, b.code, b.code
  from banaadir_sectors v
  join public.districts d on d.code = v.district_code and d.deleted_at is null
  join public.sections s on s.district_id = d.id and s.code = v.section_code and s.deleted_at is null
  join public.sectors t on t.section_id = s.id and t.code = v.code and t.deleted_at is null
  cross join lateral (
    select v.prefix || lpad(n::text, 2, '0') as code
      from unnest(coalesce(v.block_numbers, array(select generate_series(1, v.block_count)))) as n
  ) b
on conflict (district_id, code) do nothing;
"""
    Path(sys.argv[1]).write_text(sql, encoding="utf-8")
    print(f"wrote {sys.argv[1]}: {len(sections)} sections, {len(sectors)} sectors, {n_blocks} neighbourhoods")


if __name__ == "__main__":
    main()
