#!/usr/bin/env python3
"""Write the migration that stores each section's point (and a sector's own verified point)
from banaadir_locations.csv, so the map can show them as pins.

Sectors that only inherit their section's point get no pin of their own.
Usage: python3 to_app_pins.py <output .sql>
"""
import csv
import sys
from pathlib import Path

from to_app_migration import APP_DISTRICT, SECTOR_CODE_FIX, q

HERE = Path(__file__).resolve().parent


def main():
    with open(HERE / "banaadir_locations.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    sections, sectors = [], []
    for r in rows:
        dc = APP_DISTRICT[r["district_name"]]
        point = f"{r['lon']}, {r['lat']}"
        if r["coord_level"] == "section":
            sections.append(f"({q(dc)}, {q(r['section_code'])}, {point}, {q(r['coord_confidence'])}, {q(r['coord_source'])})")
        elif r["coord_level"] == "sector" and r["coord_confidence"] != "inherited":
            code = SECTOR_CODE_FIX.get((r["location_code"], r["sector_name"]), r["sector_code"])
            sectors.append(f"({q(dc)}, {q(r['section_code'])}, {q(code)}, {point}, {q(r['coord_confidence'])}, {q(r['coord_source'])})")

    sql = f"""-- ============================================================================
-- 0105 Location pins: a point for every section, and for a sector with its own verified point,
-- from frontend/location-master-data/banaadir_locations.csv (generated by to_app_pins.py).
-- Shown on the map as pins. Boundaries (geom) stay for surveyed polygons only.
-- point_confidence 'placeholder' = the district centre repeated: not a real position.
-- ============================================================================

alter table public.sections
  add column point extensions.geometry(Point, 4326),
  add column point_confidence text check (point_confidence in ('high', 'medium', 'low', 'placeholder')),
  add column point_source text;
alter table public.sectors
  add column point extensions.geometry(Point, 4326),
  add column point_confidence text check (point_confidence in ('high', 'medium', 'low', 'placeholder')),
  add column point_source text;

update public.sections s
   set point = extensions.st_setsrid(extensions.st_makepoint(v.lon, v.lat), 4326),
       point_confidence = v.confidence, point_source = v.source
  from (values
{(','+chr(10)).join('    ' + r for r in sections)}
  ) as v (district_code, code, lon, lat, confidence, source)
  join public.districts d on d.code = v.district_code
 where s.district_id = d.id and s.code = v.code;

update public.sectors t
   set point = extensions.st_setsrid(extensions.st_makepoint(v.lon, v.lat), 4326),
       point_confidence = v.confidence, point_source = v.source
  from (values
{(','+chr(10)).join('    ' + r for r in sectors)}
  ) as v (district_code, section_code, code, lon, lat, confidence, source)
  join public.districts d on d.code = v.district_code
  join public.sections s on s.district_id = d.id and s.code = v.section_code
 where t.section_id = s.id and t.code = v.code;

-- Pins for the map, as one GeoJSON FeatureCollection. Runs as the caller, so RLS applies.
create or replace function public.location_pins()
returns jsonb
language sql
stable
security invoker
set search_path = ''
as $$
  select jsonb_build_object('type', 'FeatureCollection', 'features', coalesce(jsonb_agg(f), '[]'::jsonb))
    from (
      select jsonb_build_object(
               'type', 'Feature',
               'geometry', extensions.st_asgeojson(s.point)::jsonb,
               'properties', jsonb_build_object(
                 'id', s.id, 'level', 'section', 'code', s.code, 'name_so', s.name_so, 'name_en', s.name_en,
                 'district_id', s.district_id, 'district_name_so', d.name_so,
                 'confidence', s.point_confidence, 'source', s.point_source)) as f
        from public.sections s
        join public.districts d on d.id = s.district_id
       where s.point is not null and s.deleted_at is null
      union all
      select jsonb_build_object(
               'type', 'Feature',
               'geometry', extensions.st_asgeojson(t.point)::jsonb,
               'properties', jsonb_build_object(
                 'id', t.id, 'level', 'sector', 'name_so', t.name_so, 'name_en', t.name_en,
                 'district_id', t.district_id, 'district_name_so', d.name_so,
                 'confidence', t.point_confidence, 'source', t.point_source))
        from public.sectors t
        join public.districts d on d.id = t.district_id
       where t.point is not null and t.deleted_at is null
    ) pins;
$$;

revoke execute on function public.location_pins() from public, anon;
grant execute on function public.location_pins() to authenticated;
"""
    Path(sys.argv[1]).write_text(sql, encoding="utf-8")
    print(f"wrote {sys.argv[1]}: {len(sections)} section pins, {len(sectors)} sector pins")


if __name__ == "__main__":
    main()
